#!/usr/bin/env python3
"""Deploy a built game/<name>/<name>.gba ROM (plus boxart, screenshot, metadata,
and a LICENSES.txt) onto an Anbernic RG34XX running KNULLI or muOS firmware.

Implements the deployment contract researched in
docs/research/18-device-deployment.md (§7 is the primary spec) and the single
distribution-time attribution obligation from
docs/research/20-license-attribution-obligations.md.

Two transports:
  * Wi-Fi  (default when --host is given): scp/ssh/curl to the running device.
             The nothing-by-hand path -- per-deploy work is fully automatable.
  * Offline (--sd-path): write the same file placements onto a mounted SD card,
             auto-detecting which firmware's layout the card holds.

Per firmware, the placements are:
  KNULLI  ROM  -> /userdata/roms/gba/<name>.gba
          art  -> /userdata/roms/gba/images/<name>-image.png (+ -thumb.png)
          meta -> merged into /userdata/roms/gba/gamelist.xml (upsert by <path>,
                  never blind-overwrite -- other games' entries survive)
          then -> curl http://<host>:1234/reloadgames   (Wi-Fi only)
  muOS    ROM  -> /mnt/mmc/ROMS/gba/<name>.gba
          art  -> MUOS/info/catalogue/Nintendo Game Boy Advance/{box,preview}/<name>.png
          text -> .../text/<name>.txt   (no rescan step; folder name auto-assigns)

Optional per-game deploy inputs (all optional; sensible fallbacks/defaults used):
  game/<name>/deploy/boxart.png       box art
  game/<name>/deploy/preview.png      screenshot (falls back to build/screenshot.png)
  game/<name>/deploy/description.txt  short description
  game/<name>/deploy/meta.json        {name, desc, genre, developer, publisher,
                                       players, releasedate, rating}

Usage:
    tools/deploy.py <name> --target knulli --host 192.168.1.42
    tools/deploy.py <name> --target muos   --host RG34XX
    tools/deploy.py <name> --sd-path /Volumes/SHARE          # firmware auto-detected
    tools/deploy.py <name> --target knulli --host KNULLI --dry-run

Prefer running after docker/build-and-verify.sh <name> and tools/verify_spec.py <name>
have passed. HONEST FLAG: the Wi-Fi scp/ssh/curl contract is complete against the
official docs + firmware source, but has NOT been executed against real RG34XX
hardware from this environment -- see docs/research/18 §7's final bullet.
"""
import argparse
import json
import os
import posixpath
import shlex
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# The muOS catalogue system name for GBA, verified in the assign global.ini
# (docs/research/18 §4). The catalogue folder and (for KNULLI) nothing depend on
# this exact string.
MUOS_SYSTEM = "Nintendo Game Boy Advance"

# Per-firmware defaults for SSH/SCP (docs/research/18 §7).
TARGET_DEFAULTS = {
    "knulli": {"user": "root", "password": "linux", "host": "KNULLI"},
    "muos": {"user": "root", "password": "root", "host": None},
}

# Non-interactive-friendly ssh/scp options: accept a new host key rather than
# blocking on the yes/no prompt, and don't hang forever on an unreachable host.
SSH_OPTS = ["-o", "StrictHostKeyChecking=accept-new", "-o", "ConnectTimeout=10"]

# devkitARM's gba_crt0.s is MPL 2.0 and is linked into every ROM; MPL §3.2 is
